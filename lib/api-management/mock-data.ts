/**
 * Security helper: Validates that a user-entered URL is SSRF-safe and does not target internal VPC/metadata services.
 */
export function validateSsrfSafeUrl(url: string): { safe: boolean; reason?: string } {
  try {
    const parsed = new URL(url);
    if (parsed.protocol !== "https:") {
      return { safe: false, reason: "Only encrypted HTTPS endpoints are permitted in Buymecart API registry." };
    }
    const hostname = parsed.hostname.toLowerCase();
    // Block internal loopback, private ranges, link-local, AWS metadata
    if (
      hostname === "localhost" ||
      hostname === "127.0.0.1" ||
      hostname === "169.254.169.254" ||
      hostname.startsWith("10.") ||
      hostname.startsWith("192.168.") ||
      hostname.startsWith("172.16.") ||
      hostname.endsWith(".internal") ||
      hostname.endsWith(".local")
    ) {
      return { safe: false, reason: "SSRF Protection: Access to private networks, loopbacks, and cloud metadata endpoints is strictly blocked." };
    }
    return { safe: true };
  } catch {
    return { safe: false, reason: "Malformed URL syntax." };
  }
}

